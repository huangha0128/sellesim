export function pickCountryName(code, zhName, enName, lang) {
  if (lang === 'en') return enName || zhName
  if (lang === 'ja' || lang === 'fr' || lang === 'ko' || lang === 'es') {
    const hit = CODE_MAP[code]
    if (hit && hit[lang]) return hit[lang]
  }
  return zhName || enName
}