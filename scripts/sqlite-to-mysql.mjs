#!/usr/bin/env node
/**
 * 将 Prisma + SQLite (dev.db) 存量数据导出为 MySQL 可导入的 SQL（INSERT 语句）。
 * 用于从 SQLite 平滑迁移到 MySQL：MySQL 表结构由 `prisma db push` 创建，
 * 本脚本只负责把 SQLite 中的存量数据转成 MySQL 兼容的 INSERT。
 *
 * 用法:
 *   node --experimental-sqlite sqlite-to-mysql.mjs <input.db> [output.sql]
 *
 * 转换规则:
 *   - 表名/列名与 Prisma schema 一致（Prisma 在各数据库 provider 下使用相同的列名映射）
 *   - DateTime 在 SQLite 中按 unix 毫秒整数存储，转换为 MySQL DATETIME(3)（UTC 语义）
 *   - 布尔值（MySQL TINYINT）按 0/1 透传
 *   - 输出带 SET FOREIGN_KEY_CHECKS=0，导入顺序不依赖外键
 */
import { DatabaseSync } from 'node:sqlite';
import fs from 'node:fs';
import path from 'node:path';

const dbFile = process.argv[2];
if (!dbFile) {
  console.error('用法: node sqlite-to-mysql.mjs <input.db> [output.sql]');
  process.exit(1);
}
const outFile = process.argv[3] || dbFile + '.mysql.sql';

// 按外键安全顺序导出（父表先于子表），与 Prisma schema 模型一致
const TABLES = ['Country', 'User', 'Card', 'PackagePrice', 'Setting', 'Order', 'Esim'];

const db = new DatabaseSync(dbFile, { readOnly: true });

function existsTable(name) {
  const r = db
    .prepare("SELECT 1 FROM sqlite_master WHERE type='table' AND name = ?")
    .get(name);
  return !!r;
}

function escapeStr(v) {
  // MySQL 默认把反斜杠当转义符，需同时转义 \ 与 '
  return "'" + String(v).replace(/\\/g, '\\\\').replace(/'/g, "''") + "'";
}

function toMysqlValue(v, colType) {
  if (v === null || v === undefined) return 'NULL';
  if (colType === 'DATETIME') {
    // SQLite 中 Prisma 以 unix 毫秒整数存储；兜底兼容 ISO 字符串
    const d = typeof v === 'number' ? new Date(v) : new Date(v);
    if (Number.isNaN(d.getTime())) return 'NULL';
    // toISOString: YYYY-MM-DDTHH:mm:ss.mmmZ -> YYYY-MM-DD HH:mm:ss.mmm（UTC）
    return "'" + d.toISOString().slice(0, 23).replace('T', ' ') + "'";
  }
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? '1' : '0';
  return escapeStr(v);
}

let sql = '';
sql += '-- Auto-generated by sqlite-to-mysql.mjs\n';
sql += 'SET NAMES utf8mb4;\n';
sql += 'SET FOREIGN_KEY_CHECKS=0;\n';

const summary = [];
for (const table of TABLES) {
  if (!existsTable(table)) {
    console.log(`  [skip] ${table} 不存在于源库`);
    continue;
  }
  const cols = db.prepare(`PRAGMA table_info("${table}")`).all();
  const colNames = cols.map((c) => c.name);
  const colTypes = cols.map((c) => c.type.toUpperCase());

  const rows = db.prepare(`SELECT * FROM "${table}"`).all();
  summary.push(`${table}=${rows.length}`);

  if (rows.length === 0) continue;

  const quotedCols = colNames.map((n) => '`' + n + '`').join(',');
  const chunkSize = 200;
  for (let i = 0; i < rows.length; i += chunkSize) {
    const chunk = rows.slice(i, i + chunkSize);
    const valueLines = chunk.map((r) => {
      const vals = colNames.map((n, idx) => toMysqlValue(r[n], colTypes[idx]));
      return '(' + vals.join(',') + ')';
    });
    sql += `INSERT INTO \`${table}\` (${quotedCols}) VALUES\n`;
    sql += valueLines.join(',\n') + ';\n';
  }
  console.log(`  [ok] ${table}: ${rows.length} 行`);
}

sql += 'SET FOREIGN_KEY_CHECKS=1;\n';

fs.mkdirSync(path.dirname(path.resolve(outFile)), { recursive: true });
fs.writeFileSync(outFile, sql, 'utf8');
console.log(`\n导出完成 -> ${outFile}`);
console.log('汇总: ' + summary.join(', '));
